// Helper: Verify cryptographic continuity between a list of snapshots
export function verifySnapshotsChainContinuity(snapshots: HardwareSnapshot[]): {
  isContinuityValid: boolean;
  brokenLinks: number[];
  verifiedCount: number;
} {
  if (snapshots.length <= 1) {
    return { isContinuityValid: true, brokenLinks: [], verifiedCount: snapshots.length };
  }

  const brokenLinks: number[] = [];
  for (let i = 1; i < snapshots.length; i++) {
    const prev = snapshots[i - 1];
    const curr = snapshots[i];
    // Check parentHash matching previous sealedHash
    if (curr.parentHash !== prev.sealedHash && curr.parentHash !== CANONICAL_MERKLE_ROOT) {
      brokenLinks.push(i);
    }
  }

  return {
    isContinuityValid: brokenLinks.length === 0,
    brokenLinks,
    verifiedCount: snapshots.length - brokenLinks.length,
  };
}
