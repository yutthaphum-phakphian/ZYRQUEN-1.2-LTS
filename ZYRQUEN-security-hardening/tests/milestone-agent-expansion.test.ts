import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
process.env.CODEVOICE_DURABLE_ROOT = await fs.mkdtemp(path.join(os.tmpdir(),'codevoice-expansion-'));
const { simulateAgentExecution } = await import('../server/agentSimulationEngine.ts');
const { createCoordination, claimCoordinationTask, completeCoordinationTask, loadCoordination } = await import('../server/agentCoordination.ts');
const { reconcileWorkspace } = await import('../server/stateReconciliation.ts');
const { saveWorkspace } = await import('../server/durableStore.ts');
const sim=await simulateAgentExecution({projectId:'p1',goal:'repair safely'}); assert.equal(sim.outcome,'APPROVAL_REQUIRED'); assert.ok(sim.auditHash.length===64);
const blocked=await simulateAgentExecution({projectId:'p1',goal:'critical',capabilities:['workspace.read'],maxRisk:'LOW'}); assert.equal(blocked.outcome,'SAFE_TO_APPLY');
const coord=await createCoordination({projectId:'p1',agentIds:['a','b'],tasks:[{taskId:'t1',capability:'workspace.inspect'},{taskId:'t2',capability:'repair.apply',dependsOn:['t1']}]});
const claimed=await claimCoordinationTask(coord.coordinationId,'t1','a'); assert.equal(claimed.assignments.t1,'a');
await assert.rejects(()=>claimCoordinationTask(coord.coordinationId,'t1','b'));
const done=await completeCoordinationTask(coord.coordinationId,'t1','a'); assert.equal(done.tasks.find(t=>t.taskId==='t1')?.status,'DONE');
assert.equal((await loadCoordination(coord.coordinationId))?.status,'PARTIAL');
await saveWorkspace({projectId:'p1',version:1,updatedAt:new Date().toISOString(),files:[{name:'a.txt',content:'ok'}]});
const aligned=await reconcileWorkspace({projectId:'p1',actualFiles:[{name:'a.txt',content:'ok'}]}); assert.equal(aligned.verdict,'ALIGNED');
const drift=await reconcileWorkspace({projectId:'p1',actualFiles:[{name:'a.txt',content:'changed'}]}); assert.equal(drift.verdict,'DRIFTED');
console.log('Agent expansion pack: PASS');
