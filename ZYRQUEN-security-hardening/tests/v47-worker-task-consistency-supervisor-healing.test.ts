import fs from 'node:fs/promises';
import path from 'node:path';
const root=path.resolve(process.cwd(),`.v47-test-${process.pid}-${Date.now()}`); process.env.CODEVOICE_DURABLE_ROOT=root;
const {loadDurableRecord}=await import('../server/durableStore.ts');
const {WorkerTaskConsistencySupervisor}=await import('../server/workerTaskConsistencySupervisor.ts');
await fs.rm(root,{recursive:true,force:true});
const supervisor=new WorkerTaskConsistencySupervisor({intervalMs:1000,staleMs:1000,batchLimit:10,lockTtlMs:3000,heartbeatMs:1000,orphanAfterMs:5000,failureThreshold:2,baseBackoffMs:1000,maxBackoffMs:2000,circuitOpenMs:1000,recoveryProbe:true});
await (supervisor as any).recordFailure('simulated-1');
if(supervisor.snapshot().state!=='BACKOFF') throw new Error('first failure did not backoff');
await (supervisor as any).recordFailure('simulated-2');
if(supervisor.snapshot().state!=='CIRCUIT_OPEN') throw new Error('threshold did not open circuit');
await new Promise(r=>setTimeout(r,1100));
if(!(supervisor as any).canRunNow()) throw new Error('circuit did not enter recovery probe');
if(supervisor.snapshot().state!=='HALF_OPEN') throw new Error('circuit did not enter HALF_OPEN');
await (supervisor as any).persistState('HALF_OPEN');
const restarted=new WorkerTaskConsistencySupervisor({failureThreshold:2,baseBackoffMs:1000,maxBackoffMs:2000,circuitOpenMs:1000,recoveryProbe:true});
await (restarted as any).loadPersistedState();
if(restarted.snapshot().state!=='HALF_OPEN') throw new Error('restart did not restore HALF_OPEN');
await (restarted as any).persistState('RUNNING');
await restarted.resetCircuit('test-reset');
if(restarted.snapshot().state!=='RUNNING'||restarted.snapshot().consecutiveFailures!==0) throw new Error('manual reset failed');
const state=await loadDurableRecord<any>('worker-consistency-supervisor','worker-task-consistency-supervisor-state');
if(state?.payload.state!=='RUNNING') throw new Error('reset state not durable');
await fs.rm(root,{recursive:true,force:true}); console.log('V47 durable supervisor self-healing tests: PASS');
