import { strict as assert } from 'node:assert';
import { promises as fs } from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { acquireMissionWorker, releaseMissionWorker } from '../server/missionWorkerSupervisor.ts';
import { previewDeveloperPatch } from '../server/developerPatchEngine.ts';
import { executeCrashConsistentRepair } from '../server/crashConsistentRepairCoordinator.ts';
import { inspectRepairIntegrity } from '../server/recoveryIntegrityGovernor.ts';

const root = await fs.mkdtemp(path.join(process.cwd(), '.integrity-governor-'));
const missionId = `integrity-${Date.now()}`;
await fs.writeFile(path.join(root, 'app.js'), 'bad\n', 'utf8');
const worker = await acquireMissionWorker(missionId, `worker-${Date.now()}`, 30000);
const preview = await previewDeveloperPatch({ workspaceRoot: root, operations: [{ type: 'UPDATE', target: 'app.js', content: 'good\n' }], sourceVerificationId: 'integrity-test' });
const repairId = `integrity-repair-${Date.now()}`;
await executeCrashConsistentRepair({ repairId, missionId, projectId: missionId, workspaceRoot: root, workerId: worker.workerId, leaseId: worker.leaseId, operations: [{ id: 'op-1', type: 'UPDATE', target: 'app.js', content: 'good\n' }], patchHash: preview.patchHash });
const healthy = await inspectRepairIntegrity(repairId);
assert.equal(healthy.verdict, 'HEALTHY');
assert.equal(healthy.repairStatus, 'COMMITTED');
assert.equal(healthy.transactionStatus, 'COMMITTED');
assert.equal(healthy.journalValid, true);
assert.match(healthy.auditHash, /^[a-f0-9]{64}$/);
await fs.writeFile(path.join(root, 'app.js'), 'tampered\n', 'utf8');
const drift = await inspectRepairIntegrity(repairId);
assert.equal(drift.verdict, 'CORRUPT');
assert.ok(drift.findings.some(f => f.code === 'COMMITTED_WORKSPACE_DRIFT'));
await releaseMissionWorker(missionId, worker.workerId).catch(() => undefined);
await fs.rm(root, { recursive: true, force: true });
console.log('Recovery integrity governor milestone: PASS');
